// Đóng gói mục lục từ Excel export ("Xuất mục lục hiện tại ra Excel" ở
// Cài đặt → Sao lưu & Khôi phục) thành tocBooks mặc định trong src/tocData.js.
//
// Dung: npm run toc:import-defaults -- [duong-dan/muc-luc.xlsx]
// Mac dinh lay file muc-luc-*.xlsx moi nhat trong Downloads.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require2 = createRequire(import.meta.url);
const XLSX = require2("xlsx");
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const TOC_FILE = path.join(ROOT, "src", "tocData.js");
const TAIL_MARKER = 'import { STORAGE_KEYS } from "./core/storageKeys.js";';

function findLatestExport() {
  const arg = process.argv[2];
  if (arg) {
    const p = path.resolve(arg);
    if (!fs.existsSync(p)) throw new Error(`File không tồn tại: ${p}`);
    return p;
  }
  const dl = path.join(os.homedir(), "Downloads");
  const hits = fs
    .readdirSync(dl)
    .filter((f) => /^muc-luc-.*\.xlsx$/i.test(f))
    .map((f) => ({ f, t: fs.statSync(path.join(dl, f)).mtimeMs }))
    .sort((a, b) => b.t - a.t);
  if (!hits.length) throw new Error("Không thấy muc-luc-*.xlsx trong Downloads — hãy bấm 'Xuất mục lục hiện tại ra Excel' trước.");
  return path.join(dl, hits[0].f);
}

function firstNumber(v) {
  const m = String(v ?? "").match(/\d+/);
  return m ? parseInt(m[0], 10) : null;
}

function parseExcel(file) {
  const wb = XLSX.read(fs.readFileSync(file), { type: "buffer" });
  const sheet = wb.Sheets[wb.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(sheet, { defval: "" });
  if (!rows.length) throw new Error("Excel trống");

  const booksMap = new Map();
  for (const row of rows) {
    const get = (...names) => {
      for (const n of names) {
        for (const k of Object.keys(row)) {
          if (k.trim().toLowerCase() === n) return row[k];
        }
      }
      return "";
    };
    const title = String(get("tiêu đề", "tieu de", "tên", "ten")).trim();
    const page = firstNumber(get("trang (pdf)", "trang pdf", "trang", "page"));
    if (!title || !page) continue;

    const key = String(get("mã sách", "ma sach", "mã", "ma", "key")).trim();
    if (!key) continue;
    if (!booksMap.has(key)) {
      const grade = firstNumber(get("lớp", "lop")) || 1;
      const term = firstNumber(get("tập", "tap")) || 1;
      booksMap.set(key, {
        key,
        title: String(get("tên sách", "ten sach", "tên", "ten")).trim() || key,
        grade: grade >= 1 && grade <= 5 ? grade : 1,
        subject: String(get("môn", "mon")).trim() || "Khác",
        term: term === 2 ? 2 : 1,
        items: [],
      });
    }
    const depthRaw = String(get("độ sâu", "do sau", "depth")).trim();
    const depth = depthRaw === "" ? (title.toLowerCase().startsWith("bài") || title.toLowerCase().startsWith("bai") ? 1 : 0) : Math.min(Math.max(Math.floor(Number(depthRaw) || 0), 0), 5);
    booksMap.get(key).items.push({
      title,
      sub: String(get("mô tả", "mo ta", "sub")).trim(),
      page,
      depth,
      tuann: String(get("tuần", "tuan", "tuann")).trim(),
    });
  }
  if (!booksMap.size) throw new Error("Không đọc được dòng mục lục nào");

  const books = [...booksMap.values()];
  books.sort((a, b) => a.grade - b.grade || a.subject.localeCompare(b.subject, "vi") || a.term - b.term || a.key.localeCompare(b.key));
  return books;
}

const file = findLatestExport();
const books = parseExcel(file);
const items = books.reduce((s, b) => s + b.items.length, 0);

const src = fs.readFileSync(TOC_FILE, "utf8");
const tailIdx = src.indexOf(TAIL_MARKER);
if (tailIdx < 0) throw new Error("Không tìm thấy tail logic trong tocData.js — cấu trúc file đổi, cần cập nhật script.");
const tail = src.slice(tailIdx);

const header = `// Generated by scripts/import-toc-defaults.mjs from ${path.basename(file)} — DO NOT EDIT BY HAND.
// TOC_PDF_OFFSET: printed page N maps to PDF page N + 1 (PDF page 1 is the cover).
export const tocBooks = `;
const body = JSON.stringify(books, null, 1);
fs.writeFileSync(TOC_FILE, `${header}${body};\n\n${tail}`);
console.log(`Da cap nhat tocData.js tu ${file}: ${books.length} sach / ${items} muc.`);
